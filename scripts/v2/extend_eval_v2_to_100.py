def case(
    number: int,
    group: str,
    difficulty: str,
    question: str,
    expected_metrics: list[str],
    expected_tables: list[str],
    expected_columns: list[str],
    must_include: list[str],
    *,
    requires_join: bool = True,
    requires_value_recall: bool = False,
    value_hints: list[dict[str, str]] | None = None,
    must_not_include: list[str] | None = None,
    should_exclude: list[str] | None = None,
    notes: str = "",
) -> dict[str, Any]:
    assertions: dict[str, Any] = {"must_include": must_include}
    if must_not_include:
        assertions["must_not_include"] = must_not_include
    if should_exclude:
        assertions["should_exclude"] = should_exclude

    payload: dict[str, Any] = {
        "id": f"V2_EVAL_{number:03d}",
        "group": group,
        "difficulty": difficulty,
        "question": question,
        "intent": "data_query",
        "expected_metrics": expected_metrics,
        "expected_tables": expected_tables,
        "expected_columns": expected_columns,
        "requires_join": requires_join,
        "requires_value_recall": requires_value_recall,
        "sql_assertions": assertions,
        "notes": notes,
    }
    if value_hints:
        payload["value_hints"] = value_hints
    return payload


